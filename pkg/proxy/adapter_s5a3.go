package proxy

import "net"

// ─────────────────────────────────────────────────────────────────────────────
// S5A3（DNF90 / ServerS5A3）下行适配器：**显式透传**，一个字节都不改。
//
// ── 为什么 S5A3 不需要改写 ───────────────────────────────────────────────
//
// S4A21 与 S5A9 都需要改写频道表，因为那两个服务端把"频道 IP / 端口"
// 写在**下行帧里**，而帧里的值是后端自己看到的地址。网关插在中间就必须
// 把它改成公网地址，否则客户端拿到 127.0.0.1 或内网 IP 直接连不上。
//
// S5A3 的模型不同：
//   - 频道表是服务端在 class0/op1 CHANNELINFO 里下发的
//     （body 经 rotr2 ^ 0xB5 编码的 protobuf，字段 12 = serverIP，
//      每个频道条目自带端口）；
//   - 那个 serverIP 直接来自服务端的配置项 DNFBRIDGE_SERVER_IP，
//     端口来自服务端自己的频道表；
//   - 客户端拿到什么就连什么。
//
// 也就是说 **服务端已经能把"对外地址"配成任意值**。网关只要做到两件事：
//   1. 监听与后端**相同的端口号**（1:1 透传，不做端口重映射）；
//   2. 让服务端把 DNFBRIDGE_SERVER_IP 配成网关的对外地址。
// 那么 CHANNELINFO 里天然就是网关地址，中间层没有任何需要改写的字节。
//
// 反过来，如果硬要在网关里解析并改写这个 protobuf，就等于把
// "S5A3 的频道表编码格式"复制成第二份真源 —— 服务端一改编码，网关就静默
// 改坏帧。透传是这里唯一不会腐化的选择。
//
// ── 前提条件（部署时必须满足，否则这套透传不成立）──────────────────────
//
//   * 网关与后端**不能监听同一个 host:port**。两种可用形态：
//       a) 网关在另一台机器：后端继续监听自己的地址，网关监听公网地址，
//          端口号相同（7001 / 10006~10508 / 30000~30063）；
//       b) 同一台机器：后端 DNFBRIDGE_CHANNEL_LISTEN / GAME_LISTEN_HOST
//          绑私网或 127.0.0.1，网关绑公网地址。
//   * 服务端 DNFBRIDGE_SERVER_IP 必须是**玩家实际能连到的地址**
//     （即网关的对外 IP）。
//   * 后端 GamePortMap 必须是 1:1（"10006:10006" 这种），
//     不能像 S4A21 那样做 20001→10001 的偏移 —— 偏移会让 CHANNELINFO
//     里的端口与网关监听的端口对不上。
// ─────────────────────────────────────────────────────────────────────────────

// s5a3PassthroughAdapter 把下行字节原样交回调用方。
type s5a3PassthroughAdapter struct{}

// NewS5A3PassthroughAdapter 创建 S5A3 透传适配器。
func NewS5A3PassthroughAdapter() DownlinkAdapter {
	return s5a3PassthroughAdapter{}
}

// ProcessDownlink 把 pending 原样写出，不做切帧、不解密、不改写。
//
// ★ 必须真的写出去（2026-10-22 修复）：DownlinkAdapter 的契约是
// 「适配器负责把可发送的字节交给 dst，返回值只承载**尚未处理完的残包**」
// （对照 S4A21 实现：处理完返回 nil，有半帧才返回 pending[offset:]）。
// 本函数初版直接 return pending，等于告诉调用方"这些字节还没处理完，
// 留着等下次"——copyDownlink 于是每轮 append 新数据、再把整块交回来，
// 缓冲区无界增长，客户端一个字节也收不到。
//
// 线上表现就是「接受频道信息失败」：后端已经回了 47B 应答 + 约 13.6KB
// 频道表（tcpdump 实证），网关全吞在内存里，客户端等 3 秒超时重连，
// 无限循环，永远走不到游戏口。
//
// 不切帧依然是刻意的：透传形态下网关不需要理解 S5A3 的帧布局，
// 攒多少发多少，所以**永远没有残包**，恒定返回 nil。
func (s5a3PassthroughAdapter) ProcessDownlink(pending []byte, dst net.Conn) []byte {
	if len(pending) > 0 {
		// 写失败也返回 nil：连接已坏，调用方下一轮 Read 会拿到错误并退出循环；
		// 绝不能把 pending 还回去，那正是上面那个无界增长的成因。
		// （net.Conn.Write 的契约保证 n < len 时必然带回 err，故无需处理短写。）
		_, _ = dst.Write(pending)
	}
	return nil
}
